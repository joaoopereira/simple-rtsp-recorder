#!/usr/bin/env bash
# Fake RTSP camera for local testing (Linux/macOS dev boxes).
#
#   scripts/fake-camera.sh            # serves rtsp://127.0.0.1:8554/live1.sdp
#
# Uses mediamtx as the RTSP server and ffmpeg to publish a test pattern with
# audio. mediamtx is built from source with Go if it is not on PATH (GitHub
# release downloads are often blocked in sandboxes; the Go module proxy is not).
# Ctrl+C stops both.
set -euo pipefail

MTX_VERSION=v1.9.3
BIN="${MEDIAMTX:-$(command -v mediamtx || echo "${TMPDIR:-/tmp}/mediamtx")}"

if [[ ! -x "$BIN" ]]; then
  echo "building mediamtx $MTX_VERSION → $BIN"
  src=$(GOFLAGS=-mod=mod go mod download -json "github.com/bluenviron/mediamtx@$MTX_VERSION" | sed -n 's/.*"Dir": "\(.*\)".*/\1/p')
  work=$(mktemp -d)
  cp -r "$src/." "$work" && chmod -R u+w "$work"
  # Files normally generated by `go generate` upstream.
  echo "$MTX_VERSION" > "$work/internal/core/VERSION"
  : > "$work/internal/servers/hls/hls.min.js"
  (cd "$work" && go build -o "$BIN" .)
  rm -rf "$work"
fi

cd "$(mktemp -d)"
# Minimal config: accept any path, disable protocols we don't need.
cat > mediamtx.yml <<'YML'
rtmp: no
hls: no
webrtc: no
srt: no
paths:
  all_others:
YML
"$BIN" mediamtx.yml >mediamtx.log 2>&1 &
MTX_PID=$!
trap 'kill $MTX_PID 2>/dev/null' EXIT
sleep 1

echo "fake camera: rtsp://127.0.0.1:8554/live1.sdp (host 127.0.0.1, port 8554, path live1.sdp, no credentials)"
ffmpeg -hide_banner -loglevel error -re \
  -f lavfi -i "testsrc2=size=1280x720:rate=25" \
  -f lavfi -i "sine=frequency=440:sample_rate=48000" \
  -c:v libx264 -preset ultrafast -tune zerolatency -g 50 -pix_fmt yuv420p \
  -c:a aac -b:a 64k \
  -f rtsp -rtsp_transport tcp rtsp://127.0.0.1:8554/live1.sdp
